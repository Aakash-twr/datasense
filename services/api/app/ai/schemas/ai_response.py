"""AI response and request schemas."""

from __future__ import annotations

import enum
from datetime import datetime
from typing import Any

from pydantic import BaseModel, Field


class ResponseType(enum.StrEnum):
    """Classification of AI response."""

    CONVERSATIONAL = "conversational"
    SQL_QUERY = "sql_query"
    CLARIFICATION = "clarification"
    EXPLANATION = "explanation"
    UNSUPPORTED = "unsupported"


class VisualizationRecommendation(BaseModel):
    """Recommended chart configuration based on query intent and column types."""

    chart_type: str = Field(description="Recommended chart type: 'bar', 'line', or 'pie'")
    x_axis: str = Field(description="Column name to use for x-axis / dimension")
    y_axis: str = Field(description="Column name to use for y-axis / metric")
    title: str | None = Field(default=None, description="Suggested chart title")


class AICopilotResponse(BaseModel):
    """Structured Pydantic response generated by Gemini / LangChain."""

    response_type: ResponseType = Field(
        default=ResponseType.CONVERSATIONAL,
        description="The type of AI response: 'conversational', 'sql_query', 'clarification', 'explanation', or 'unsupported'",
    )
    message: str = Field(
        description="Natural-language response, overview, explanation, or conversational reply for the user",
    )
    generated_sql: str | None = Field(
        default=None,
        description="DuckDB SQL analytical query draft, if a database query was requested or implied",
    )
    sql_explanation: str | None = Field(
        default=None,
        description="Clear explanation of what the SQL query does, tables accessed, and logic used",
    )
    assumptions: list[str] = Field(
        default_factory=list,
        description="Assumptions made when interpreting the question, selecting columns, or formulating SQL",
    )
    requires_clarification: bool = Field(
        default=False,
        description="Set to true if user question is ambiguous or lacks required details to produce accurate SQL",
    )
    clarification_question: str | None = Field(
        default=None,
        description="Clarification question to present to user if requires_clarification is true",
    )
    visualization_recommendation: VisualizationRecommendation | None = Field(
        default=None,
        description="Recommended chart visualization for query results, if applicable",
    )
    suggested_follow_up_questions: list[str] = Field(
        default_factory=list,
        description="2 to 4 relevant follow-up questions the user can ask next to explore their data further",
    )


class AIStatusResponse(BaseModel):
    """Safe public status of AI copilot services."""

    enabled: bool
    configured: bool
    model: str
    available: bool
    privacy_acknowledged: bool
    message: str


class AIConversationCreateRequest(BaseModel):
    """Request to start a new chat conversation."""

    title: str = "New Analytics Chat"
    dataset_ids: list[str] = Field(default_factory=list)


class AIConversationUpdateRequest(BaseModel):
    """Request to update conversation title or selected datasets."""

    title: str | None = None
    dataset_ids: list[str] | None = None


class AIMessageRequest(BaseModel):
    """User message submission."""

    message: str = Field(min_length=1, max_length=4000)


class AIMessageResponse(BaseModel):
    """A message in the conversation thread."""

    id: str
    conversation_id: str
    role: str
    content: str
    structured_metadata: dict[str, Any] | None = None
    generated_sql: str | None = None
    sql_explanation: str | None = None
    sql_validation_status: str | None = None
    created_at: datetime


class AIConversationResponse(BaseModel):
    """Conversation details with message history."""

    id: str
    organization_id: str
    project_id: str
    user_id: str
    title: str
    selected_dataset_ids: list[str]
    created_at: datetime
    updated_at: datetime
    messages: list[AIMessageResponse] = Field(default_factory=list)


class AIConversationListItem(BaseModel):
    """Summary item for conversation listings."""

    id: str
    title: str
    selected_dataset_ids: list[str]
    created_at: datetime
    updated_at: datetime
    message_count: int = 0


class AIConversationListResponse(BaseModel):
    """Paginated list of conversations."""

    items: list[AIConversationListItem]
    total: int
    page: int
    page_size: int
    total_pages: int


class AIInsightItem(BaseModel):
    """Single suggested insight or analytical angle."""

    title: str
    description: str
    category: str
    suggested_question: str
    suggested_sql: str | None = None


class AIInsightResponse(BaseModel):
    """Collection of AI-generated insights for selected datasets."""

    dataset_id: str
    dataset_name: str
    insights: list[AIInsightItem]


class AISQLExplanationRequest(BaseModel):
    """Request to explain or optimize an existing SQL query."""

    sql: str = Field(min_length=1)
    dataset_ids: list[str] = Field(default_factory=list)


class AISQLExplanationResponse(BaseModel):
    """Detailed plain-English breakdown of a SQL query."""

    explanation: str
    accessed_tables: list[str]
    applied_filters: list[str]
    aggregations_and_calculations: list[str]
    suggested_improvements: list[str] = Field(default_factory=list)
    improved_sql: str | None = None


class AIPrivacyAcknowledgeResponse(BaseModel):
    """Confirmation that user acknowledged privacy terms."""

    acknowledged: bool
    acknowledged_at: datetime
